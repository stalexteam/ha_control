/** Palette as CSS custom properties for the chrome (`--ps-<key>`). */
export function paletteVars(p: PlanPalette): string {
  return Object.entries(p)
    .filter(([, v]) => typeof v === 'string')
    .map(([k, v]) => `--ps-${k}:${v}`)
    .join(';');
}

